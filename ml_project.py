# ------------------------------------------------------------
# 2. GENERATE A SYNTHETIC DATASET
# ------------------------------------------------------------

rows = []

for career, profile in career_profiles.items():
    for _ in range(200):
        student_skills = np.clip(
            np.array(profile) +
            np.random.normal(0, 1.15, len(skills)),
            0, 5
        )

