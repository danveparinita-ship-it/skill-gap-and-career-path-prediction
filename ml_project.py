# 5. CAREER PREDICTION AND RECOMMENDATION
# ------------------------------------------------------------

def career_recommendation(student_profile, target_career=None):

    input_df = pd.DataFrame(
        [[student_profile[s] for s in skills]],
        columns=skills
    )

    # Predict the most suitable career category
    predicted_career = model.predict(input_df)[0]

    probabilities = model.predict_proba(input_df)[0]

    scores = pd.DataFrame({
        "Career": model.classes_,
        "Prediction Score (%)": np.round(probabilities * 100, 2)
    }).sort_values(
        "Prediction Score (%)",
        ascending=False
    ).reset_index(drop=True)

    print("\n" + "=" * 65)
    print("CAREER PREDICTION RESULTS")
    print("=" * 65)

    print("\nPredicted Career:", predicted_career)

    print("\nCareer Prediction Scores:")
    display(scores)

    if target_career is None:
        target_career = predicted_career

    print("\nSelected Career Goal:", target_career)

    # Analyze gaps against the selected career
    results, readiness = analyze_skill_gap(
        student_profile,
        target_career
    )

    print(f"\nSkill Readiness Score: {readiness}%")

    print("\nDetailed Skill Gap Report:")
    display(results)

    # Recommend learning priorities
    missing = results[results["Skill Gap"] > 0]

    print("\nPERSONALIZED LEARNING ROADMAP")
    print("-" * 40)

    if missing.empty:
        print("All modeled career skill requirements are met.")
    else:
        for i, (_, row) in enumerate(missing.iterrows(), start=1):
            skill_name = row["Skill"].replace("_", " ")
            print(
                f"{i}. Improve {skill_name}: "
                f"Current {row['Current Level']}/5 -> "
                f"Target {row['Required Level']}/5"
            )

    # Visualize skill gaps
    plot_data = results.sort_values(
        "Required Level",
        ascending=True
    )

    positions = np.arange(len(plot_data))

    plt.figure(figsize=(11, 7))

    plt.barh(
        positions - 0.18,
        plot_data["Current Level"],
        height=0.35,
        label="Current Skill"
    )

    plt.barh(
        positions + 0.18,
        plot_data["Required Level"],
        height=0.35,
        label="Required Skill"
    )

    plt.yticks(
        positions,
        plot_data["Skill"].str.replace("_", " ")
    )

    plt.xlabel("Proficiency Level (0 to 5)")
    plt.title(f"Skill Gap Analysis - {target_career}")
    plt.xlim(0, 5.5)
    plt.legend()
    plt.tight_layout()
    plt.show()

    # Display feature importance from the trained model
    importances = pd.DataFrame({
        "Skill": skills,
        "Importance": model.feature_importances_
    }).sort_values("Importance", ascending=True)

    plt.figure(figsize=(10, 6))
    plt.barh(
        importances["Skill"].str.replace("_", " "),
        importances["Importance"]
    )
    plt.xlabel("Feature Importance")
    plt.title("Skills Influencing Career Predictions")
    plt.tight_layout()
    plt.show()

    return predicted_career, results, readiness

