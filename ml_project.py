print(classification_report(y_test, y_pred, zero_division=0))

# ------------------------------------------------------------
# 4. SKILL GAP ANALYSIS FUNCTION
# ------------------------------------------------------------

def analyze_skill_gap(student_profile, target_career):

    required = np.array(career_profiles[target_career])
    current = np.array([student_profile[s] for s in skills])

    gaps = np.maximum(required - current, 0)

    results = pd.DataFrame({
        "Skill": skills,
        "Current Level": current,
        "Required Level": required,
        "Skill Gap": gaps
    })

    results["Status"] = np.where(
        results["Skill Gap"] == 0,
        "Requirement Met",
        "Needs Improvement"
    )

    results = results.sort_values(
        by="Skill Gap",
        ascending=False
    ).reset_index(drop=True)

    total_required = required.sum()

    readiness = (
        100 * np.minimum(current, required).sum() / total_required
        if total_required > 0 else 100
    )

    return results, round(readiness, 2)

